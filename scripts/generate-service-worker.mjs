import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");

export const CORE_ROUTES = [
  "/",
  "/airflow-ducts",
  "/cooling-loads",
  "/field-diagnostics",
  "/heating-systems",
  "/building-science",
  "/manifest.webmanifest",
  "/icon.svg",
  "/offline.html",
];

export function extractOfflineRoutes(registrySource) {
  const entries = registrySource.match(/^  \{\r?\n    id:[\s\S]*?^  \},?$/gm) || [];
  return entries.flatMap((entry) => {
    const route = entry.match(/^    route: "([^"]+)",?$/m)?.[1];
    const status = entry.match(/^    status: "([^"]+)",?$/m)?.[1];
    const eligible = entry.match(/^    offlineEligible: (true|false),?$/m)?.[1] === "true";
    return route && eligible && (status === "production" || status === "beta") ? [route] : [];
  });
}

export function renderServiceWorker(routes) {
  const assets = [...new Set([...CORE_ROUTES, ...routes])].sort();
  const version = createHash("sha256").update(JSON.stringify(assets)).digest("hex").slice(0, 12);
  return `/* Generated by scripts/generate-service-worker.mjs. Do not edit manually. */
const CACHE_NAME = "hvaclogic-offline-${version}";
const PRECACHE_URLS = ${JSON.stringify(assets, null, 2)};

async function precacheApp() {
  const cache = await caches.open(CACHE_NAME);
  await cache.addAll(PRECACHE_URLS);
  const documents = await Promise.all(PRECACHE_URLS.filter((url) => !url.includes(".")).map((url) => cache.match(url)));
  const assetUrls = new Set();
  for (const response of documents) {
    if (!response) continue;
    const html = await response.text();
    for (const match of html.matchAll(/(?:src|href)=["']([^"']+)["']/g)) {
      const assetUrl = new URL(match[1], self.location.origin);
      if (assetUrl.origin === self.location.origin && assetUrl.pathname.startsWith("/_next/")) assetUrls.add(assetUrl.pathname + assetUrl.search);
    }
  }
  if (assetUrls.size) await cache.addAll([...assetUrls]);
}

self.addEventListener("install", (event) => {
  event.waitUntil(precacheApp());
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith("hvaclogic-offline-") && key !== CACHE_NAME).map((key) => caches.delete(key)))));
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  if (event.request.mode === "navigate") {
    event.respondWith(fetch(event.request, { cache: "no-store" }).then((response) => {
      if (!response.ok && self.navigator.onLine === false) return caches.match("/offline.html");
      if (response.ok) caches.open(CACHE_NAME).then((cache) => cache.put(event.request, response.clone()));
      return response;
    }).catch(async () => (await caches.match(event.request)) || (await caches.match(url.pathname)) || caches.match("/offline.html")));
    return;
  }

  event.respondWith(caches.match(event.request).then((cached) => {
    const network = fetch(event.request).then((response) => {
      if (response.ok && response.type === "basic") caches.open(CACHE_NAME).then((cache) => cache.put(event.request, response.clone()));
      return response;
    });
    return cached || network;
  }));
});
`;
}

export async function generateServiceWorker(root = projectRoot) {
  const registryPath = path.join(root, "src", "lib", "data", "calculators-registry.ts");
  const outputPath = path.join(root, "public", "sw.js");
  const source = await readFile(registryPath, "utf8");
  const routes = extractOfflineRoutes(source);
  await writeFile(outputPath, renderServiceWorker(routes), "utf8");
  return routes;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const routes = await generateServiceWorker();
  console.log(`Generated public/sw.js with ${routes.length} calculator routes.`);
}
